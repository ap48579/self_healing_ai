"""Episode schema — the Action Arc, per coding_agent_plan.md / cortex_reasoning.md."""

from __future__ import annotations

import time
import uuid
from enum import Enum
from typing import Optional

from pydantic import BaseModel, Field


class Outcome(str, Enum):
    SUCCESS = "success"
    PARTIAL = "partial"
    FAILURE = "failure"


class ActionArcStep(BaseModel):
    action: str
    tool_used: str
    output: str


class HealerAttempt(BaseModel):
    hypothesis: str
    fix: str
    outcome: str


class CostActual(BaseModel):
    input_tokens: int = 0
    output_tokens: int = 0
    thinking_tokens: int = 0


class Episode(BaseModel):
    """One complete record of a task: how it was solved, or why it failed.

    Field names match the "Action Arc — Updated Schema" in coding_agent_plan.md.
    """

    episode_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    created_at: float = Field(default_factory=time.time)

    domain: str = "coding"
    scope: str = "default"  # project / user / org — gates retrieval (Trust Policies)

    problem_summary: str
    initial_plan: Optional[str] = None
    action_arc: list[ActionArcStep] = Field(default_factory=list)
    healer_attempts: list[HealerAttempt] = Field(default_factory=list)

    outcome: Outcome = Outcome.SUCCESS
    final_solution: Optional[str] = None

    # Generated by the model after the episode ends — not hand-written.
    abstracted_pattern: Optional[str] = None  # feeds Intuition
    failure_summary: Optional[str] = None  # feeds Caution, only if outcome != success

    distilled_learnings: list[str] = Field(default_factory=list)
    cost_actual: CostActual = Field(default_factory=CostActual)

    # Predicted vs actual difficulty — drives the salience boost on write-back.
    predicted_complexity: Optional[str] = None  # simple | medium | complex
    healer_attempt_count: int = 0

    def salience_boost(self) -> float:
        """Surprise = predicted vs. actual difficulty mismatch. Higher = stronger
        initial groove weight on write-back. See cortex_reasoning.md."""
        if self.predicted_complexity is None:
            return 0.0
        predicted_easy = self.predicted_complexity == "simple"
        actually_hard = self.healer_attempt_count >= 3
        predicted_hard = self.predicted_complexity == "complex"
        actually_easy = self.healer_attempt_count == 0
        if (predicted_easy and actually_hard) or (predicted_hard and actually_easy):
            return 0.5
        return 0.0
