"""Write-back — persist an episode and update the groove graph.

Takes an already-fully-formed Episode (abstracted_pattern / failure_summary
already generated by the caller's LLM layer — Cortex itself stays
model-agnostic, per the "inference-time scaffolding only" philosophy).
"""

from __future__ import annotations

from .graph import MemoryGraph
from .retrieval import RetrievalContext
from .schema import Episode, Outcome
from .store import CortexStore


def write_back(
    store: CortexStore,
    graph: MemoryGraph,
    episode: Episode,
    retrieved: RetrievalContext | None = None,
) -> None:
    """Step 4 of the per-task loop: store the episode, then reinforce or
    weaken the groove edges for whatever was retrieved this round."""

    store.write_episode(episode)

    graph.add_node(
        episode.episode_id,
        node_type="episode",
        domain=episode.domain,
        scope=episode.scope,
        outcome=episode.outcome.value,
    )

    success = episode.outcome == Outcome.SUCCESS
    base_weight = 0.5 + episode.salience_boost()

    if episode.abstracted_pattern:
        pattern_node = f"pattern::{abs(hash(episode.abstracted_pattern))}"
        graph.add_node(pattern_node, node_type="pattern", text=episode.abstracted_pattern)
        graph.add_edge(
            episode.episode_id,
            pattern_node,
            edge_type="instance_of",
            weight=base_weight,
            topic=episode.domain,
        )

    if retrieved is not None:
        for other_id in retrieved.all_surfaced_episode_ids:
            if other_id == episode.episode_id or other_id not in graph.graph:
                continue
            graph.reinforce(
                episode.episode_id,
                other_id,
                edge_type="co_retrieved_with",
                success=success,
            )
            graph.reinforce(
                other_id,
                episode.episode_id,
                edge_type="co_retrieved_with",
                success=success,
            )

        # Caution hits that were surfaced but the episode failed anyway despite
        # the warning being heeded is *not* a contradiction signal on its own —
        # but a Caution hit whose advice was followed and still led to failure
        # is exactly the "contradicts" case: the heuristic recommended by a
        # pattern node led somewhere bad.
        if not success:
            for hit in retrieved.intuition_hits:
                pattern_text = hit["document"]
                pattern_node = f"pattern::{abs(hash(pattern_text))}"
                if pattern_node in graph.graph:
                    graph.add_edge(
                        episode.episode_id,
                        pattern_node,
                        edge_type="contradicts",
                        weight=0.6,
                        topic=episode.domain,
                    )
